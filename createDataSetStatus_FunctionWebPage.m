% Mapa interactivo de la trayectoria (Leaflet)
if ~isempty(lon)
    fprintf(fid,'%s\n', ...
        '<div class="figura">', ...
        '<div id="mapa"></div>', ...
        '<div class="pie">', ...
        '<h3>Mapa interactivo de la trayectoria</h3>', ...
        ['<p>Posiciones de todos los perfiles realizados por el perfilador. El color indica la fecha del perfil (misma escala que la figura de la trayectoria), ', ...
        'el círculo con borde blanco es la posición de despliegue y el de borde negro la última posición. ', ...
        'Pinche en el mapa para activar el zoom y el desplazamiento, y en cada posición para ver el número de ciclo y la fecha.</p>'], ...
        '</div>', ...
        '</div>', ...
        '<script>', ...
        ['var trayectoria = ' TrayectoriaJS ';'], ...
        ['var gradiente = "' GradienteJS '";'], ...
        'var mapa = L.map("mapa", {scrollWheelZoom: false, dragging: false, touchZoom: false, doubleClickZoom: false, fullscreenControl: true});', ...
