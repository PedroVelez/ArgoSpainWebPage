        '};', ...
        'capas["Batimetría"].addTo(mapa);', ...
        'L.control.layers(capas, null, {position: "topleft"}).addTo(mapa);', ...
        'L.control.scale({imperial: false}).addTo(mapa);', ...
        'var puntos = trayectoria.map(function(p){ return [p[0], p[1]]; });', ...
        'L.polyline(puntos, {color: "#555555", weight: 1, opacity: 0.8}).addTo(mapa);', ...
        'trayectoria.forEach(function(p, i){', ...
        '  var extremo = (i === 0 || i === trayectoria.length - 1);', ...
        '  L.circleMarker([p[0], p[1]], {radius: extremo ? 7 : 4, color: i === 0 ? "#ffffff" : (extremo ? "#000000" : p[4]), weight: extremo ? 2 : 1, fillColor: p[4], fillOpacity: 0.9})', ...
        '   .bindPopup("<b>Ciclo " + p[2] + "</b><br>" + p[3] + "<br>" + p[0].toFixed(3) + "&deg;N, " + p[1].toFixed(3) + "&deg;E")', ...
        '   .addTo(mapa);', ...
        '});', ...
        'mapa.fitBounds(L.latLngBounds(puntos).pad(0.15), {maxZoom: 8});', ...
        'var leyenda = L.control({position: "bottomright"});', ...
        'leyenda.onAdd = function(){', ...
        '  var div = L.DomUtil.create("div", "mapa-leyenda");', ...
        '  div.innerHTML = "<b>Fecha del perfil</b><div class=\"barra\" style=\"background: linear-gradient(to right," + gradiente + ")\"></div>" +', ...
        '    "<div class=\"fechas\"><span>" + trayectoria[0][3] + "</span><span>" + trayectoria[trayectoria.length - 1][3] + "</span></div>";', ...
        '  return div;', ...
        '};', ...
        'leyenda.addTo(mapa);', ...
        '// Interaccion: click (o dos dedos en movil) activa el mapa; al salir se desactiva', ...
        'var contenedor = mapa.getContainer();', ...
        'var aviso = document.createElement("div");', ...
        'aviso.className = "mapa-aviso";', ...
        'aviso.textContent = window.innerWidth <= 767 ? "Usa dos dedos para mover el mapa" : "Haz click para activar el mapa";', ...
        'contenedor.appendChild(aviso);', ...
        'function activa(){ mapa.dragging.enable(); mapa.touchZoom.enable(); mapa.scrollWheelZoom.enable(); mapa.doubleClickZoom.enable(); aviso.style.display = "none"; }', ...
        'function desactiva(){ mapa.dragging.disable(); mapa.touchZoom.disable(); mapa.scrollWheelZoom.disable(); mapa.doubleClickZoom.disable(); aviso.style.display = "flex"; }', ...
        'mapa.on("click", activa);', ...
        'contenedor.addEventListener("mouseleave", function(){ if(!mapa.isFullscreen || !mapa.isFullscreen()){ desactiva(); } });', ...
        'mapa.on("fullscreenchange", function(){ if(mapa.isFullscreen()){ activa(); } });', ...
        'var temporizador;', ...
        'contenedor.addEventListener("touchstart", function(e){ if(e.touches.length === 2){ clearTimeout(temporizador); activa(); } });', ...
